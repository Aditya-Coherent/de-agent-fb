"""The market run trackers (open them in Excel), run in this order:

    AiAgentsFleet/AllMarkets/markets_priority1.csv   Priority 1 (100 titles) -- generated first
    AiAgentsFleet/AllMarkets/markets_priority2.csv   Priority 2 (400 titles)

Every market has a status label, so a market whose report was generated is never generated again:

    pending    not run yet
    generated  report built and passed the release gate   -> always skipped
    draft      report built but failed the release gate (saved as .DRAFT.docx) -> skipped unless --redo
    failed     the run crashed                            -> retried by the next batch

`sync` also labels any market whose report already exists on disk (e.g. one generated by hand), so the
file always matches the output folder. If a CSV is open in Excel when the batch writes, the update goes
to its .pending.csv (e.g. markets_priority1.pending.csv) and is merged the next time the tracker is written.
"""
from __future__ import annotations

import csv
import re
from datetime import datetime
from pathlib import Path

FLEET = Path(__file__).resolve().parent.parent
TRACKERS = [FLEET / "AllMarkets" / "markets_priority1.csv",   # in run order: Priority 1 before Priority 2
            FLEET / "AllMarkets" / "markets_priority2.csv"]
STATUS_COLS = ["status", "generated_on", "minutes", "report"]
DONE = {"generated"}


def slug(name: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", name.strip().lower()).strip("-")


def report_paths(s: str) -> tuple[Path, Path]:
    docx = FLEET / "output" / s / f"{s}-cmi-whitepaper.docx"
    return docx, docx.with_name(docx.stem + ".DRAFT.docx")


def load(path: Path) -> list[dict]:
    with path.open(encoding="utf-8-sig", newline="") as f:
        rows = list(csv.DictReader(f))
    pend = path.with_suffix(".pending.csv")
    if pend.exists():                                       # updates made while the CSV was open in Excel
        with pend.open(encoding="utf-8-sig", newline="") as f:
            upd = {r["slug"]: r for r in csv.DictReader(f)}
        for r in rows:
            if r["slug"] in upd:
                r.update({k: upd[r["slug"]].get(k, "") for k in STATUS_COLS})
    for r in rows:
        for k in STATUS_COLS:
            r.setdefault(k, "")
        r["status"] = r["status"] or "pending"
    return rows


def save(rows: list[dict], path: Path) -> bool:
    """Writes the tracker; when Excel has it open, writes the status updates to the .pending.csv instead
    (merged on the next load). Returns True when the main file was written."""
    cols = [c for c in rows[0] if c not in STATUS_COLS] + STATUS_COLS
    pend = path.with_suffix(".pending.csv")
    try:
        with path.open("w", encoding="utf-8-sig", newline="") as f:
            w = csv.DictWriter(f, fieldnames=cols, extrasaction="ignore")
            w.writeheader()
            w.writerows(rows)
        pend.unlink(missing_ok=True)
        return True
    except PermissionError:
        with pend.open("w", encoding="utf-8-sig", newline="") as f:
            w = csv.DictWriter(f, fieldnames=["slug"] + STATUS_COLS, extrasaction="ignore")
            w.writeheader()
            w.writerows(r for r in rows if r["status"] != "pending")
        return False


def mark(row: dict, status: str, minutes: float | None = None, when: datetime | None = None) -> None:
    docx, draft = report_paths(row["slug"])
    row["status"] = status
    row["generated_on"] = (when or datetime.now()).strftime("%Y-%m-%d %H:%M") if status in ("generated", "draft") else ""
    row["minutes"] = f"{minutes:.1f}" if minutes is not None else row.get("minutes", "")
    row["report"] = (str(docx.relative_to(FLEET)) if status == "generated" else
                     str(draft.relative_to(FLEET)) if status == "draft" else "")


def sync(rows: list[dict]) -> int:
    """Labels every market whose report exists on disk; returns how many labels changed."""
    n = 0
    for r in rows:
        docx, draft = report_paths(r["slug"])
        want = "generated" if docx.exists() else "draft" if draft.exists() else None
        if not want:
            continue
        when = datetime.fromtimestamp((docx if want == "generated" else draft).stat().st_mtime)
        if r["status"] != want or r["generated_on"] != when.strftime("%Y-%m-%d %H:%M"):   # a regenerated report
            mark(r, want, minutes=float(r["minutes"]) if r.get("minutes") else None, when=when)
            n += 1
    return n
